#!/usr/bin/env python3
"""Render Synapse, Element, LiveKit and Alertmanager config from .env and secrets/."""

from __future__ import annotations

import json
import os
import re
import stat
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SERVER_NAME_RE = re.compile(r"^[a-z0-9]([a-z0-9-]{0,62}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,62}[a-z0-9])?)+$")


def dq(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def read_env(path: Path) -> dict[str, str]:
    data: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
            value = value[1:-1]
        data[key.strip()] = value
    return data


def read_secret(name: str) -> str:
    path = ROOT / "secrets" / name
    if not path.is_file():
        sys.exit(f"missing {path}. Run: make init")
    value = path.read_text(encoding="utf-8").strip()
    if not value:
        sys.exit(f"empty secret: {path}")
    return value


def write_private(path: Path, content: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    os.chmod(path, mode)


def tailscale_ipv4() -> str:
    override = os.environ.get("TAILSCALE_IPV4", "").strip()
    if override:
        return override
    ip_file = ROOT / "secrets" / "tailscale_ipv4"
    if ip_file.is_file():
        return ip_file.read_text(encoding="utf-8").strip()
    return ""


