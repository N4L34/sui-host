def element_config(env: dict[str, str], server: str) -> str:
    brand = env.get("ELEMENT_BRAND") or "Свои"
    base = f"https://{server}"
    web = f"https://{server}:8443"
    calls = env.get("ENABLE_CALLS", "false").lower() == "true"
    body = {
        "default_server_config": {
            "m.homeserver": {"base_url": base, "server_name": server}
        },
        "disable_custom_urls": True,
        "disable_guests": True,
        "disable_3pid_login": True,
        "disable_login_language_selector": False,
        "brand": brand,
        "default_country_code": "RU",
        "default_federate": False,
        "default_theme": "dark",
        "show_labs_settings": False,
        "room_directory": {"servers": []},
        "permalink_prefix": web,
        "integrations_ui_url": None,
        "integrations_rest_url": None,
        "integrations_widgets_urls": [],
        "setting_defaults": {"breadcrumbs": True},
        "element_call": {"brand": brand, "use_exclusively": calls},
        "jitsi": {"preferred_domain": ""},
        "map_style_url": "",
    }
    return json.dumps(body, ensure_ascii=False, indent=2) + "\n"


def livekit_yaml(server_ip: str, secret: str) -> str:
    if not re.fullmatch(r"[0-9]{1,3}(\.[0-9]{1,3}){3}", server_ip):
        sys.exit(
            "ENABLE_CALLS=true but there is no Tailscale IPv4. "
            "Run `tailscale ip -4` and write it to secrets/tailscale_ipv4, "
            "or export TAILSCALE_IPV4."
        )
    return f"""# Generated. ICE address is the tailnet address, never the public VPS address.
port: 7880
bind_addresses:
  - ""
rtc:
  tcp_port: 7881
  port_range_start: 50000
  port_range_end: 50100
  use_external_ip: false
  node_ip: {server_ip}
  enable_loopback_candidate: false
  # Answer checks that reach this node. The 15s hangup on 1.9.0 was a
  # missing /rtc/v1; lite was already on and did not stop it. Stay on the
  # pinned image until a newer tag survives a real call.
  use_ice_lite: true
# Prometheus metrics. Not published on the host; Prometheus scrapes it
# on the compose network. The old prometheus_port key still works and warns.
prometheus:
  port: 6789
room:
  auto_create: false
keys:
  matrixrtc: {dq(secret)}
webhook:
  api_key: matrixrtc
  urls:
    - http://lk-jwt:8080/sfu_webhook
"""


def caddyfile() -> str:
    # Clients call https://<server>:8444/livekit/jwt/... and wss://<server>:8444/livekit/sfu/...
    # The backends listen at the root, so the prefix is removed here.
    return """# Plain HTTP. Tailscale serve terminates TLS on :8444 and forwards here.
:80 {
\thandle /livekit/jwt* {
\t\turi strip_prefix /livekit/jwt
\t\treverse_proxy lk-jwt:8080
\t}
\thandle /livekit/sfu* {
\t\turi strip_prefix /livekit/sfu
\t\treverse_proxy livekit:7880
\t}
\thandle {
\t\treverse_proxy livekit:7880
\t}
}
"""


def caddyfile_dial() -> str:
    # lk-jwt looks up OpenID userinfo at https://<server-name>:8448 and calls
    # LiveKit at https://<server-name>:8444. Both names resolve to the Tailscale
    # address. Tailscale drops those packets when they come from Docker, so
    # this proxy answers them inside the compose network. The certificate is
    # the node's own Tailscale cert. Nothing here is published on the host.
    return """{
	admin off
	auto_https off
}
:443 {
	tls /certs/fullchain.pem /certs/privkey.pem
	reverse_proxy synapse:8008
}
:8448 {
	tls /certs/fullchain.pem /certs/privkey.pem
	reverse_proxy synapse:8008
}
:8444 {
	tls /certs/fullchain.pem /certs/privkey.pem
	reverse_proxy calls-proxy:80
}
"""


def alertmanager(env: dict[str, str]) -> str:
    webhook = env.get("ALERT_WEBHOOK_URL", "").strip()
    if webhook:
        receiver = f"""receivers:
  - name: default
    webhook_configs:
      - url: {dq(webhook)}
        send_resolved: true
"""
    else:
        receiver = """receivers:
  - name: default
"""
    return f"""# Generated.
route:
  receiver: default
  group_by: [alertname]
  group_wait: 30s
  group_interval: 5m
  repeat_interval: 4h

{receiver}"""


def guard_server_name(server: str) -> None:
    stamp = ROOT / "secrets" / "server_name"
    if not stamp.exists():
        return
    previous = stamp.read_text(encoding="utf-8").strip()
    if previous and previous != server:
        sys.exit(
            "MATRIX_SERVER_NAME changed from "
            f"{previous} to {server}. The Matrix server name is permanent. "
            "Restoring the old name is the safe action. A new name is a new server."
        )


def main() -> None:
    env_path = ROOT / ".env"
    if not env_path.is_file():
        sys.exit("missing .env. Run: cp .env.example .env")
    env = read_env(env_path)
    server = env.get("MATRIX_SERVER_NAME", "").strip().rstrip(".")
    if not SERVER_NAME_RE.fullmatch(server):
        sys.exit(
            "MATRIX_SERVER_NAME must be a lowercase DNS name such as "
            "messenger.example.com"
        )
    if server.endswith(".example.ts.net") or "tailnet-name" in server:
        print(
            "warning: MATRIX_SERVER_NAME still looks like the example. "
            "Set it to this node's MagicDNS name before the first account.",
            file=sys.stderr,
        )
    guard_server_name(server)

    out = ROOT / "deploy" / "rendered"
    out.mkdir(parents=True, exist_ok=True)
    os.chmod(out, 0o700)
    textfile = out / "textfile"
    textfile.mkdir(parents=True, exist_ok=True)

    hs = homeserver(env, server)
    required = [
        "federation_domain_whitelist: []",
        "enable_registration: false",
        "url_preview_enabled: false",
        "encryption_enabled_by_default: true",
        "names: [client]",
    ]
    missing = [item for item in required if item not in hs]
    if missing:
        sys.exit(f"renderer dropped required settings: {missing}")
    if "names: [client, federation]" in hs or "names: [federation]" in hs:
        sys.exit("renderer exposed a federation listener")

    # Directory is 0700. The file itself is 0644 so the container user can read it.
    write_private(out / "homeserver.yaml", hs, 0o644)
    write_private(out / "element-config.json", element_config(env, server), 0o644)
    json.loads((out / "element-config.json").read_text(encoding="utf-8"))
    write_private(out / "alertmanager.yml", alertmanager(env), 0o644)

    if env.get("ENABLE_CALLS", "false").lower() == "true":
        ip = tailscale_ipv4()
        livekit_secret = read_secret("livekit_secret")
        write_private(out / "livekit.yaml", livekit_yaml(ip, livekit_secret), 0o644)
        write_private(out / "Caddyfile.calls", caddyfile(), 0o644)
        write_private(out / "Caddyfile.dial", caddyfile_dial(), 0o644)
        write_private(
            ROOT / "secrets" / "calls.env",
            "LIVEKIT_SECRET=" + dq(livekit_secret) + "\n",
            0o600,
        )
    placeholder = "tailnet-name" in server or server.endswith(".example.ts.net")
    stamp = ROOT / "secrets" / "server_name"
    if not placeholder and not stamp.exists():
        stamp.write_text(server + "\n", encoding="utf-8")
        os.chmod(stamp, stat.S_IRUSR | stat.S_IWUSR)
    print(f"rendered config for {server}")


if __name__ == "__main__":
    main()
